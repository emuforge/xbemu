//! The embedded 8x8 bitmap font: printable ASCII, 0x20 to 0x7E.
//!
//! The glyph data is the basic-latin table of `font8x8` by Daniel Hepper
//! (`font8x8_basic.h`, <https://github.com/dhepper/font8x8>), license: public
//! domain. That table is in turn based on `font8_8.asm` by Marcel Sondaar,
//! built from the public-domain IBM VGA font listings, license: public domain.
//! The rows below are copied unchanged, with two exceptions: the control
//! characters and DEL were dropped, and the capital `V` was redrawn for this
//! crate (the original differs from `U` only in its last two rows, and
//! "VSync" and "KVM" read as "USync" and "KUM" at menu size).
//!
//! Each glyph is eight rows, top first. In a row, bit 0 (the least
//! significant) is the leftmost pixel.

/// Width of a glyph cell in font pixels.
pub const GLYPH_W: i32 = 8;
/// Height of a glyph cell in font pixels.
pub const GLYPH_H: i32 = 8;

/// The rows of the glyph for `c`. A character outside printable ASCII gets
/// the glyph of `?`, so arbitrary strings (a GPU name, a title name) always
/// render as something.
#[must_use]
pub fn glyph(c: char) -> &'static [u8; 8] {
    let code = c as u32;
    let code = if (0x20..=0x7E).contains(&code) { code } else { '?' as u32 };
    &GLYPHS[(code - 0x20) as usize]
}


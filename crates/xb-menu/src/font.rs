#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_blank_and_every_other_glyph_has_ink() {
        assert_eq!(glyph(' '), &[0; 8]);
        for code in 0x21..=0x7Eu8 {
            assert!(glyph(code as char).iter().any(|&row| row != 0), "{:?} is blank", code as char);
        }
    }

    #[test]
    fn characters_outside_printable_ascii_fall_back_to_the_question_mark() {
        for c in ['\0', '\n', '\x7F', 'é', '日'] {
            assert_eq!(glyph(c), glyph('?'));
        }
    }

    #[test]
    fn capital_i_is_symmetric_about_its_stem() {
        // The glyph is known by shape rather than by its bytes: a serifed I
        // is a bar, a stem and a bar, and the stem is narrower than the bars.
        let g = glyph('I');
        assert_eq!(g[0], g[6]);
        assert!(g[1..6].iter().all(|&row| row == g[1]));
        assert!(g[1].count_ones() < g[0].count_ones());
        assert_eq!(g[1] & g[0], g[1]);
    }
}
